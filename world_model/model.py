"""
Section U / Blueprint Feature 34 — DreamerV3-inspired Market World Model.

This is the *consumer-facing* wrapper around the RSSM defined in
`ml.architectures.WorldModelBundle`. Audit Issue #2 upgrade:

  - Previous architecture (all of encoder + transition + reward) was three
    separate `Sequential(Linear, ReLU, Linear)` MLPs. The "transition" was a
    1-step MLP, not recurrent — there was no real notion of dynamics over time.
  - New architecture is a proper RSSM (Hafner et al., DreamerV3 / Nature 2025):
    GRU-based deterministic recurrence + stochastic Gaussian latent + prior
    and posterior dynamics + symlog reward head + continue head.

External API kept stable (callers in `memory/write.py`, `self_play/mars.py`,
`memory/cognitive/memrl.py`, the test suite, and Audit Issue #1's online-learning
fix continue to work without changes):

  encode(observation: dict) -> list[float]
  predict_next_state(latent: list[float], action: str) -> list[float]
  predict_reward(latent: list[float], action: str) -> float
  imagine_trajectory(action, n_steps, initial_obs) -> dict
  update_on_trade_close(predicted_outcome, actual_pnl, latent) -> dict

Latent representation changed under the hood: 32 floats → 96 floats
(deter[64] + stoch[32], concatenated). Callers treat it as an opaque list, so
this is invisible to them — but the model file format DOES change, so the
checkpoint must be regenerated by pretrainer.

Online-learning scope (unchanged from previous fix): only the REWARD HEAD is
trained from actual_pnl at trade close. The RSSM's encoder/GRU/prior/posterior
need either supervised next-state targets (we don't capture them yet) or
DreamerV3-style imagined-rollout loss with KL balancing — both deferred.
"""
from pathlib import Path
import structlog

log = structlog.get_logger()

_MODEL_PATH = Path("models/world_model.pth")

_bundle       = None
_optimizer    = None
_last_mtime   = 0.0
_LR           = 1e-4   # conservative — single-sample SGD on each trade close, no batch averaging
_GRAD_CLIP    = 1.0    # max gradient norm — prevents single noisy trade from breaking weights
_PNL_SCALE    = 50.0   # actual_pnl ∼ [-50, +50] → reward target ∼ [-1, 1]

# Action one-hot encoding — fixed order: open_long, open_short, hold, close
_ACTIONS = ("open_long", "open_short", "hold", "close")


def _action_onehot(action: str):
    """Return torch tensor [1, 4] for the action; default to hold."""
    import torch
    idx = _ACTIONS.index(action) if action in _ACTIONS else 2  # default hold
    v = [0.0] * len(_ACTIONS)
    v[idx] = 1.0
    return torch.tensor([v], dtype=torch.float32)


def _load() -> None:
    """Lazy load + mtime-based reload. Resets optimizer when weights change."""
    global _bundle, _optimizer, _last_mtime
    if not _MODEL_PATH.exists():
        return
    mtime = _MODEL_PATH.stat().st_mtime
    if _bundle is not None and mtime == _last_mtime:
        return
    try:
        import torch
        from ml.architectures import WorldModelBundle, inject_into_main
        inject_into_main()
        checkpoint = torch.load(_MODEL_PATH, map_location="cpu", weights_only=False)

        bundle = WorldModelBundle()
        if isinstance(checkpoint, dict) and "encoder" in checkpoint and \
                isinstance(checkpoint["encoder"], torch.nn.Module):
            # Legacy dict-of-modules — incompatible shape (old MLP transition vs new
            # GRU+prior+posterior). Refuse to load; pretrainer must regenerate.
            log.warning("world_model_legacy_format_detected_must_repretrain",
                        path=str(_MODEL_PATH))
            return
        if isinstance(checkpoint, dict):
            # state_dict — try strict load; on shape mismatch, fall back to fresh init.
            try:
                bundle.load_state_dict(checkpoint)
            except Exception as exc:
                log.warning("world_model_state_dict_mismatch_using_fresh",
                            error=str(exc)[:200])
                bundle = WorldModelBundle()  # fresh random init
        else:
            log.warning("world_model_legacy_full_pickle_must_repretrain")
            return

        bundle.eval()
        _bundle = bundle
        _last_mtime = mtime
        _optimizer = None
        log.info("world_model_loaded_rssm",
                 mtime=round(mtime, 2),
                 deter_dim=bundle.DETER_DIM,
                 stoch_dim=bundle.STOCH_DIM,
                 latent_dim=bundle.LATENT_DIM)
    except Exception as exc:
        log.warning("world_model_load_failed_using_fallback", error=str(exc)[:200])


def _save_bundle() -> None:
    """Persist current bundle to disk atomically (temp file + rename)."""
    global _last_mtime
    if _bundle is None:
        return
    try:
        import torch
        tmp = _MODEL_PATH.with_suffix(".pth.tmp")
        torch.save(_bundle.state_dict(), tmp)
        tmp.replace(_MODEL_PATH)
        _last_mtime = _MODEL_PATH.stat().st_mtime
    except Exception as exc:
        log.warning("world_model_save_failed", error=str(exc)[:200])


def _get_optimizer():
    """Lazy-init Adam on reward head only — online learning scope per design note."""
    global _optimizer
    if _optimizer is None and _bundle is not None:
        import torch
        _optimizer = torch.optim.Adam(_bundle.reward.parameters(), lr=_LR)
    return _optimizer


# ─────────────────────────────────────────────────────────────────────────────
# RSSM-core online training (Session 2026-05-21 cont. 5).
# Trains encoder + action_embed + GRU + prior + posterior + reward head jointly
# from each closed trade using a 2-step DreamerV3-style KL-balanced loss.
# ─────────────────────────────────────────────────────────────────────────────
_rssm_optimizer = None
_RSSM_LR        = 3e-5    # gentler than reward-only LR — RSSM core has more params
_KL_BALANCE     = 0.8     # DreamerV3 default — α weights stop-grad-posterior side
_KL_FREE_BITS   = 1.0     # nats per dim, prevents KL collapse
_KL_WEIGHT      = 0.5     # caller-controllable balance vs reward MSE


def _get_rssm_optimizer():
    """Adam over encoder + action_embed + GRU + prior + posterior + reward."""
    global _rssm_optimizer
    if _rssm_optimizer is None and _bundle is not None:
        import torch
        params = (
            list(_bundle.encoder.parameters())
            + list(_bundle.action_embed.parameters())
            + list(_bundle.gru.parameters())
            + list(_bundle.prior.parameters())
            + list(_bundle.posterior.parameters())
            + list(_bundle.reward.parameters())
        )
        _rssm_optimizer = torch.optim.Adam(params, lr=_RSSM_LR)
    return _rssm_optimizer


def _embed_obs(obs: dict):
    """Encode an observation dict to embed tensor [1, EMBED_DIM]. Symlog input
    transform — same as `encode()` external API uses."""
    import torch
    vals = [float(v) for v in obs.values() if isinstance(v, (int, float))]
    vals = (vals + [0.0] * _bundle.OBS_DIM)[:_bundle.OBS_DIM]
    x = torch.tensor(vals, dtype=torch.float32).unsqueeze(0)
    x = torch.sign(x) * torch.log1p(torch.abs(x))
    return _bundle.encoder(x)


def _kl_diag_normal(mu_q, std_q, mu_p, std_p):
    """KL(N(mu_q, std_q²) || N(mu_p, std_p²)) summed over the last dimension."""
    import torch
    return (
        torch.log(std_p / std_q)
        + (std_q ** 2 + (mu_q - mu_p) ** 2) / (2.0 * std_p ** 2)
        - 0.5
    ).sum(dim=-1)


def train_rssm_step(entry_obs: dict, action: str,
                    exit_obs: dict, actual_pnl: float) -> dict:
    """U-05b: Train RSSM core (encoder + GRU + prior + posterior + reward head)
    from one closed trade using a 2-step DreamerV3-style KL-balanced loss.

    Step 1: observe(entry_obs, entry_action)   → (h_1, z_1, prior_1, post_1)
    Step 2: observe(exit_obs,  "hold")         → (h_2, z_2, prior_2, post_2)

    Losses:
      KL_balance = α · KL(sg(post_2) || prior_2)
                 + (1-α) · KL(post_2 || sg(prior_2))
      reward     = MSE(reward_head(h_2, z_2), symlog(target_pnl_normalized))
      total      = _KL_WEIGHT · KL_balance + reward

    Reward loss anchors the latent — without it, KL alone would collapse the
    encoder. KL forces the prior to predict where the posterior actually lands
    after the trade. Both required for meaningful RSSM training.

    Behavior matrix mirrors `update_on_trade_close`:
      - F34 deactivated by governance      → {"status": "f34_inactive"}
      - model not loaded                   → {"status": "no_model"}
      - happy path                         → {"status": "updated", "loss": …}
    """
    try:
        from feature_governance.registry import is_active
        if not is_active("F34"):
            return {"status": "f34_inactive"}
    except Exception:
        pass

    _load()
    if _bundle is None:
        return {"status": "no_model"}

    try:
        import torch, time
        opt = _get_rssm_optimizer()
        if opt is None:
            return {"status": "no_rssm_optimizer"}

        _bundle.train()
        opt.zero_grad()

        embed_entry = _embed_obs(entry_obs)
        embed_exit  = _embed_obs(exit_obs)

        # ── Step 1: observe entry tick with the open action ──────────────
        deter_0, stoch_0 = _bundle.initial_state(batch=1)
        action_oh_open = _action_onehot(
            action if action in _ACTIONS else "hold"
        )
        deter_1, stoch_1, *_ = _bundle.observe_step(
            deter_0, stoch_0, action_oh_open, embed_entry
        )

        # ── Step 2: observe exit tick — bot held the position in between ─
        action_oh_hold = _action_onehot("hold")
        deter_2, stoch_2, prior_m2, prior_s2, post_m2, post_s2 = \
            _bundle.observe_step(deter_1, stoch_1, action_oh_hold, embed_exit)

        # KL-balanced consistency loss (per-sample → mean over batch=1)
        kl_prior_side = _kl_diag_normal(
            post_m2.detach(), post_s2.detach(), prior_m2, prior_s2
        )
        kl_post_side  = _kl_diag_normal(
            post_m2, post_s2, prior_m2.detach(), prior_s2.detach()
        )
        # Free-bits clamp prevents the KL from collapsing to zero
        kl_prior_side = torch.clamp(kl_prior_side, min=_KL_FREE_BITS)
        kl_post_side  = torch.clamp(kl_post_side,  min=_KL_FREE_BITS)
        loss_kl = (
            _KL_BALANCE * kl_prior_side
            + (1.0 - _KL_BALANCE) * kl_post_side
        ).mean()

        # Reward anchor — same symlog scheme as update_on_trade_close uses
        target_natural = max(-1.0, min(1.0, actual_pnl / _PNL_SCALE))
        target_symlog  = _bundle.symlog(
            torch.tensor([[target_natural]], dtype=torch.float32)
        )
        full_2 = torch.cat([deter_2, stoch_2], dim=-1)
        pred_symlog = _bundle.reward(full_2)
        loss_reward = torch.nn.functional.mse_loss(pred_symlog, target_symlog)

        loss = _KL_WEIGHT * loss_kl + loss_reward
        loss.backward()
        # Same grad-norm cap as reward-only path — single noisy trade can't blow weights
        all_params = (
            list(_bundle.encoder.parameters())
            + list(_bundle.action_embed.parameters())
            + list(_bundle.gru.parameters())
            + list(_bundle.prior.parameters())
            + list(_bundle.posterior.parameters())
            + list(_bundle.reward.parameters())
        )
        torch.nn.utils.clip_grad_norm_(all_params, max_norm=_GRAD_CLIP)
        opt.step()
        _bundle.eval()
        _save_bundle()

        loss_val   = float(loss.item())
        kl_val     = float(loss_kl.item())
        reward_val = float(loss_reward.item())
        log.info("world_model_rssm_updated",
                 loss=round(loss_val, 6),
                 loss_kl=round(kl_val, 6),
                 loss_reward=round(reward_val, 6),
                 actual_pnl=round(actual_pnl, 4),
                 action=action)

        try:
            import redis_client as _rcw
            _r = _rcw.get()
            _r.incr("world_model:rssm_updates_count")
            _r.set("world_model:rssm_last_loss", loss_val)
            _r.set("world_model:rssm_last_kl",   kl_val)
            _r.set("world_model:rssm_last_reward_loss", reward_val)
            _r.set("world_model:rssm_last_ts",   int(time.time()))
        except Exception:
            pass

        return {
            "status":     "updated",
            "loss":        loss_val,
            "loss_kl":     kl_val,
            "loss_reward": reward_val,
        }
    except Exception as exc:
        log.error("world_model_rssm_backprop_failed", error=str(exc)[:200])
        return {"status": "rssm_backprop_failed", "error": str(exc)[:200]}


