def encode(observation: dict) -> list[float]:
    """U-01: Encode raw market observation → latent state (deter+stoch concatenated).

    Returns list[float] of length 96 (was 32 in the old MLP architecture). External
    callers treat this as an opaque blob and pass it back to predict_* — they don't
    care about the dimensionality.

    First call from a fresh observation starts a new RSSM trajectory with zero
    initial deter+stoch and uses the POSTERIOR (observation-conditioned) to produce
    the first latent. This is the right behavior at trade-open time.
    """
    _load()
    if _bundle is None:
        # Hash fallback — only used when model file is missing / failed to load.
        import hashlib
        obs_str = str(sorted(observation.items()))
        h = int(hashlib.md5(obs_str.encode()).hexdigest(), 16)
        return [(h >> i & 0xFF) / 255.0 for i in range(_FALLBACK_DIM)]

    try:
        import torch
        vals = [float(v) for v in observation.values() if isinstance(v, (int, float))]
        vals = (vals + [0.0] * _bundle.OBS_DIM)[:_bundle.OBS_DIM]
        x = torch.tensor(vals, dtype=torch.float32).unsqueeze(0)
        # DreamerV3-style symlog input transform: handles arbitrary observation
        # scales (price=50000, volume=1e6, sentiment=0.5 all coexist in obs).
        # Without this, raw price/volume → Xavier-init weights → encoder output
        # of magnitude 1e5 → GRU amplifies → latent of magnitude 1e5 → reward
        # head saturates regardless of warmup. symlog: sign(x)*log1p(|x|).
        x = torch.sign(x) * torch.log1p(torch.abs(x))

        with torch.no_grad():
            embed = _bundle.encoder(x)
            deter, stoch = _bundle.initial_state(batch=1)
            # Use a neutral "hold" action for the initial observation step.
            action_oh = _action_onehot("hold")
            new_deter, new_stoch, *_ = _bundle.observe_step(deter, stoch, action_oh, embed)
        latent = torch.cat([new_deter, new_stoch], dim=-1).squeeze(0).tolist()
        return latent
    except Exception as exc:
        log.error("world_model_encode_failed", error=str(exc)[:200])
        return [0.0] * (WORLDMODEL_LATENT_DIM if _bundle is None else _bundle.LATENT_DIM)


def predict_next_state(latent: list[float], action: str) -> list[float]:
    """U-02: One imagined transition step — uses RSSM prior (no observation).
    Splits incoming latent into (deter, stoch), runs imagine_step, returns new latent."""
    _load()
    if _bundle is None:
        # Hash-fallback: trivial drift
        action_bias = {"open_long": 0.5, "open_short": -0.5, "hold": 0.0, "close": -0.25}
        a = action_bias.get(action, 0.0)
        return [l + a * 0.01 for l in latent]

    try:
        import torch
        d_dim = _bundle.DETER_DIM
        s_dim = _bundle.STOCH_DIM
        if len(latent) < d_dim + s_dim:
            # Old 32-dim latent from a legacy stored prediction. Pad with zeros.
            latent = latent + [0.0] * (d_dim + s_dim - len(latent))
        deter = torch.tensor(latent[:d_dim],            dtype=torch.float32).unsqueeze(0)
        stoch = torch.tensor(latent[d_dim:d_dim+s_dim], dtype=torch.float32).unsqueeze(0)
        action_oh = _action_onehot(action)
        with torch.no_grad():
            new_deter, new_stoch, *_ = _bundle.imagine_step(deter, stoch, action_oh)
        return torch.cat([new_deter, new_stoch], dim=-1).squeeze(0).tolist()
    except Exception as exc:
        log.error("world_model_transition_failed", error=str(exc)[:200])
        return latent


def predict_reward(latent: list[float], action: str) -> float:
    """U-03: Reward head — symlog-space prediction converted back to natural reward.
    Action parameter is kept in signature for backward compat but the new RSSM's
    reward depends only on (deter, stoch); the action's influence flows through
    predict_next_state."""
    _load()
    if _bundle is None:
        action_bias = {"open_long": 0.1, "open_short": 0.1, "hold": 0.0, "close": -0.05}
        return action_bias.get(action, 0.0)

    try:
        import torch
        d_dim = _bundle.DETER_DIM
        s_dim = _bundle.STOCH_DIM
        if len(latent) < d_dim + s_dim:
            latent = latent + [0.0] * (d_dim + s_dim - len(latent))
        deter = torch.tensor(latent[:d_dim],            dtype=torch.float32).unsqueeze(0)
        stoch = torch.tensor(latent[d_dim:d_dim+s_dim], dtype=torch.float32).unsqueeze(0)
        with torch.no_grad():
            r = _bundle.reward_from_state(deter, stoch)
        return float(r.squeeze())
    except Exception as exc:
        log.error("world_model_reward_failed", error=str(exc)[:200])
        return 0.0


def imagine_trajectory(action: str, n_steps: int, initial_obs: dict) -> dict:
    """U-04: Chain encoder + imagined rollout + reward for n_steps; return outcome distribution."""
    latent = encode(initial_obs)
    rewards = []

    for _ in range(n_steps):
        r = predict_reward(latent, action)
        rewards.append(r)
        latent = predict_next_state(latent, action)

    if not rewards:
        return {"mean_pnl": 0.0, "uncertainty": 1.0, "prob_profit": 0.5, "latent": latent}

    mean_r = sum(rewards) / len(rewards)
    variance = sum((r - mean_r) ** 2 for r in rewards) / len(rewards)
    prob_profit = sum(1 for r in rewards if r > 0) / len(rewards)

    return {
        "mean_pnl": round(mean_r, 4),
        "uncertainty": round(variance ** 0.5, 4),
        "prob_profit": round(prob_profit, 4),
        "latent": latent,
    }


def update_on_trade_close(predicted_outcome: dict, actual_pnl: float,
                          latent: list[float] | None = None) -> dict:
    """U-05: Online learning — Adam SGD step on the reward head from prediction error.

    Trained quantity = reward head only. RSSM core (GRU + prior + posterior) is
    NOT trained from trade close events alone — that needs supervised next-state
    targets or full DreamerV3 imagined-rollout loss with KL balancing. Documented
    in the module header.

    Behavior matrix (unchanged from previous fix, refactored for new shapes):
      - F34 deactivated by governance         → log + return {"status": "f34_inactive"}
      - no latent provided (legacy callers)   → log error magnitude only
      - model not loaded                      → log only
      - happy path                            → forward → MSE in symlog space → backprop → save
    """
    pred = float(predicted_outcome.get("mean_pnl", 0.0))
    error = abs(pred - actual_pnl)

    try:
        from feature_governance.registry import is_active
        if not is_active("F34"):
            log.debug("world_model_update_gated_off", error=round(error, 4))
            return {"status": "f34_inactive"}
    except Exception:
        pass

    if latent is None:
        log.debug("world_model_no_latent_log_only",
                  predicted=round(pred, 4), actual=round(actual_pnl, 4), error=round(error, 4))
        return {"status": "no_latent"}

    _load()
    if _bundle is None:
        log.debug("world_model_no_model_log_only", error=round(error, 4))
        return {"status": "no_model"}

    try:
        import torch
        opt = _get_optimizer()
        if opt is None:
            return {"status": "no_optimizer"}

        d_dim = _bundle.DETER_DIM
        s_dim = _bundle.STOCH_DIM
        if len(latent) < d_dim + s_dim:
            latent = latent + [0.0] * (d_dim + s_dim - len(latent))
        deter = torch.tensor(latent[:d_dim],            dtype=torch.float32).unsqueeze(0)
        stoch = torch.tensor(latent[d_dim:d_dim+s_dim], dtype=torch.float32).unsqueeze(0)

        # Target = symlog-transformed normalized PnL, clipped to [-1, 1].
        target_natural = max(-1.0, min(1.0, actual_pnl / _PNL_SCALE))
        target_symlog = _bundle.symlog(torch.tensor([[target_natural]], dtype=torch.float32))

        _bundle.reward.train()
        opt.zero_grad()
        full = torch.cat([deter, stoch], dim=-1)
        # Predict in symlog space — train against symlog target directly. NO clamp here:
        # clamping the prediction kills the gradient at the boundary, so a randomly-
        # saturated reward head could never recover. Inference uses clamp to bound the
        # returned natural-scale value, but SGD needs unclamped gradient flow.
        pred_symlog = _bundle.reward(full)
        loss = torch.nn.functional.mse_loss(pred_symlog, target_symlog)
        # Blueprint F17 EWC penalty: λ/2 · Σ F_i (θ_i - θ*_i)². Adds only when Fisher
        # has been snapshotted (post-300-trade sleep consolidation). Otherwise no-op.
        # Sleep consolidation runs in a separate Celery worker process — the brain's
        # in-memory _ewc_fisher dict starts empty, so we load_state() from Redis on
        # demand. Cheap (one Redis GET) and idempotent.
        try:
            from feature_governance.registry import is_active as _fg_active_f17
            from ml import continual_learning as _cl
            if _fg_active_f17("F17"):
                if not _cl._ewc_fisher:
                    _cl.load_state()
                if _cl._ewc_fisher and _cl._ewc_params_star:
                    ewc_pen = torch.tensor(0.0)
                    for name, p in _bundle.reward.named_parameters():
                        if name in _cl._ewc_fisher and name in _cl._ewc_params_star:
                            f = torch.tensor(_cl._ewc_fisher[name], dtype=p.dtype, device=p.device)
                            s = torch.tensor(_cl._ewc_params_star[name], dtype=p.dtype, device=p.device)
                            ewc_pen = ewc_pen + (f * (p - s) ** 2).sum()
                    loss = loss + 500.0 * ewc_pen  # λ=1000 → λ/2=500
        except Exception:
            pass
        loss.backward()
        # Grad-norm clipping is what actually bounds single-trade weight movement.
        torch.nn.utils.clip_grad_norm_(_bundle.reward.parameters(), max_norm=_GRAD_CLIP)
        opt.step()
        _bundle.reward.eval()

        _save_bundle()

        loss_val = float(loss.item())
        log.info("world_model_weights_updated",
                 actual_pnl=round(actual_pnl, 4),
                 predicted_pnl=round(pred, 4),
                 target_natural=round(target_natural, 4),
                 loss_symlog=round(loss_val, 6),
                 error_pnl=round(error, 4))
        return {
            "status": "updated",
            "loss": loss_val,
            "target_reward": target_natural,
            "error_pnl": error,
        }
    except Exception as exc:
        log.error("world_model_backprop_failed", error=str(exc)[:200])
        return {"status": "backprop_failed", "error": str(exc)[:200]}


def plan_best_action(observation: dict,
                     candidate_actions: list[str] | None = None,
                     n_rollouts: int = 32,
                     horizon: int = 8) -> dict | None:
    """U-07: Model-Predictive Planning (MPP) — picks the best action by imagined rollout.

    Blueprint Feature 34 / Section 8.8 explicitly demand a "policy optimizer: plans
    sequences of actions through imagined futures (model-predictive planning)" and
    that the Brain "selects the action whose imagined outcomes are most consistently
    profitable across the simulated trajectories". Prior to this function the world
    model could only score a single given action via `imagine_trajectory` — there was
    no action selection, so the world model never informed entry decisions.

    For each candidate action:
      1. Encode the initial observation once → (deter0, stoch0) via posterior.
      2. Sample `n_rollouts` stochastic trajectories of length `horizon` using the
         RSSM prior (stoch is resampled from N(prior_mean, prior_std) each step).
      3. Sum natural-scale reward across the trajectory.
      4. Mean across rollouts = action score; std across rollouts = uncertainty.

    Returns argmax action plus full score dict so the caller can apply a softer
    multiplier rather than a hard veto (see signals/engine.py).

    Returns None when the RSSM bundle is in fallback (no model loaded) so callers
    can degrade gracefully — never crash the hot path.
    """
    _load()
    if _bundle is None:
        return None

    if candidate_actions is None:
        candidate_actions = ["open_long", "open_short", "hold"]

    try:
        import torch
        # 1) Encode observation → posterior (deter0, stoch0). Same symlog input
        #    transform as encode(), so MPP and post-hoc training see the same
        #    observation distribution.
        vals = [float(v) for v in observation.values() if isinstance(v, (int, float))]
        vals = (vals + [0.0] * _bundle.OBS_DIM)[:_bundle.OBS_DIM]
        x = torch.tensor(vals, dtype=torch.float32).unsqueeze(0)
        x = torch.sign(x) * torch.log1p(torch.abs(x))

        with torch.no_grad():
            embed = _bundle.encoder(x)
            deter0, stoch0 = _bundle.initial_state(batch=1)
            init_action = _action_onehot("hold")
            deter0, stoch0, *_ = _bundle.observe_step(deter0, stoch0, init_action, embed)

        action_scores: dict[str, float] = {}
        action_stds: dict[str, float] = {}

        with torch.no_grad():
            for action in candidate_actions:
                action_oh = _action_onehot(action)
                cum_rewards: list[float] = []
                for _ in range(n_rollouts):
                    deter, stoch = deter0.clone(), stoch0.clone()
                    total_r = 0.0
                    for _step in range(horizon):
                        # imagine_step resamples stoch from N(prior_mean, prior_std),
                        # so each rollout traces a different imagined future even
                        # with the same action sequence.
                        deter, stoch, *_ = _bundle.imagine_step(deter, stoch, action_oh)
                        r = _bundle.reward_from_state(deter, stoch).clamp(-100.0, 100.0)
                        total_r += float(r.squeeze())
                    cum_rewards.append(total_r)
                mean_r = sum(cum_rewards) / len(cum_rewards) if cum_rewards else 0.0
                var_r = (sum((r - mean_r) ** 2 for r in cum_rewards) / len(cum_rewards)
                         if cum_rewards else 0.0)
                action_scores[action] = round(mean_r, 4)
                action_stds[action] = round(var_r ** 0.5, 4)

        # cont. 52 — no-trade-baseline normalisation. Before this block the
        # raw `reward_from_state` outputs were the only signal MPP used, and
        # those are biased negative by the world-model's training prior (most
        # historical 8-step rollouts net negative after fees). The bias made
        # `mean_reward` uniformly negative for ALL actions, which (a) leaks
        # a misleading scalar into the consume side and (b) loses information
        # about *relative* preference (open vs hold) — the only thing MPP is
        # supposed to inform.
        #
        # Fix: subtract the `hold` action's score from each candidate. Hold
        # becomes the baseline at 0; positive relative score ⇒ this trade
        # beats doing nothing in the imagined trajectories. Action selection
        # is mathematically invariant to a uniform shift (argmax is the same),
        # so this changes only the reported scalar, not the picked action.
        # Source: arXiv 2506.04358 (risk-aware RL reward formulation).
        hold_score = action_scores.get("hold", 0.0)
        relative_scores = {a: round(s - hold_score, 4)
                           for a, s in action_scores.items()}
        best_action = max(relative_scores, key=relative_scores.get)
        mean_reward = relative_scores[best_action]
        uncertainty = action_stds[best_action]

        # Durable evidence keys — feature_health.F34 check reads these to verify
        # the planning side (separate from the post-hoc training side, which uses
        # world_model:prediction:<trade_id>).
        try:
            import time as _t
            import redis_client
            r_cli = redis_client.get()
            r_cli.incr("world_model:mpp_calls_count")
            r_cli.set("world_model:mpp_last_ts", str(int(_t.time())))
            r_cli.set("world_model:mpp_last_best_action", best_action)
            r_cli.set("world_model:mpp_last_mean_reward", str(round(mean_reward, 4)))
            r_cli.set("world_model:mpp_last_uncertainty", str(round(uncertainty, 4)))
        except Exception:
            pass

        return {
            "best_action": best_action,
            "action_scores": action_scores,
            "relative_scores": relative_scores,
            "action_stds": action_stds,
            "mean_reward": mean_reward,
            "uncertainty": uncertainty,
            "n_rollouts": n_rollouts,
            "horizon": horizon,
        }
    except Exception as exc:
        log.warning("plan_best_action_failed", error=str(exc)[:200])
        return None


def prescreen_strategy(strategy_code: str, n_simulations: int = 50) -> tuple[bool, float]:
    """U-06: Pre-screen new strategy using imagined trajectories."""
    import random
    results = []
    for _ in range(n_simulations):
        obs = {"price": random.uniform(100, 50000), "volume": random.uniform(1e6, 1e9)}
        traj = imagine_trajectory("open_long", 10, obs)
        results.append(traj["mean_pnl"])

    avg_pnl = sum(results) / len(results) if results else 0
    passes = avg_pnl > -0.05
    return passes, round(avg_pnl, 4)


